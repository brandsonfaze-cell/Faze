export function getPersonalizedDailySelection(
  topics: FocusTopic[],
  dateStr: string
): { verse: DailyVerseEntry; chapter: ScriptureChapter } {
  const activeTopics = topics.length > 0 ? topics : (['peace', 'wisdom'] as FocusTopic[]);
  const matchingVerses = DAILY_VERSES.filter((v) => activeTopics.includes(v.topic));
  const pool = matchingVerses.length > 0 ? matchingVerses : DAILY_VERSES;

  // Deterministic day-of-year hash so the daily verse stays consistent all day
  const daySeed = dateStr.split('').reduce((acc, ch) => acc * 31 + ch.charCodeAt(0), 7);
  const verse = pool[Math.abs(daySeed) % pool.length];
  const chapter =
    SCRIPTURE_CHAPTERS.find((c) => c.id === verse.chapterId) ?? SCRIPTURE_CHAPTERS[0];

  return { verse, chapter };
}
